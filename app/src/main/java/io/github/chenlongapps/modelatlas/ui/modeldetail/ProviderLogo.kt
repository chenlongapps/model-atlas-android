@DrawableRes
internal fun providerLogoResOrNull(providerId: String?): Int? = ProviderLogos[providerId]

@DrawableRes
internal fun providerLogoRes(providerId: String?): Int =
    providerLogoResOrNull(providerId) ?: R.drawable.ic_provider_logo_fallback

/** 旁侧已有服务商名称，logo 仅作装饰；固定白底、不随主题着色或在 RTL 下镜像。 */
@Composable
internal fun ProviderLogo(providerId: String, modifier: Modifier = Modifier) {
    Box(
        modifier = modifier
            .size(40.dp)
            .clip(RoundedCornerShape(25))
            .background(Color.White)
            .testTag("provider-logo:$providerId"),
        contentAlignment = Alignment.Center,
    ) {
        Image(
            painter = painterResource(providerLogoRes(providerId)),
            contentDescription = null,
            modifier = Modifier.fillMaxSize(0.8f)
                .testTag(if (providerLogoResOrNull(providerId) == null) "provider-logo-fallback" else "provider-logo"),
        )
    }
}
